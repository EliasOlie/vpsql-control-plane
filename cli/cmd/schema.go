package cmd

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"
	"text/tabwriter"

	"github.com/spf13/cobra"
)

var (
	flagFormat      string
	flagTableFilter string
)

func pgTypeToTs(pgType string) string {
	lower := strings.ToLower(strings.TrimSpace(pgType))
	if strings.HasSuffix(lower, "[]") {
		base := strings.TrimSuffix(lower, "[]")
		return pgTypeToTs(base) + "[]"
	}
	if strings.HasPrefix(lower, "int") || strings.HasPrefix(lower, "smallint") ||
		strings.HasPrefix(lower, "bigint") || strings.HasPrefix(lower, "decimal") ||
		strings.HasPrefix(lower, "numeric") || strings.HasPrefix(lower, "real") ||
		strings.HasPrefix(lower, "double") || strings.HasPrefix(lower, "float") ||
		strings.HasPrefix(lower, "serial") {
		return "number"
	}
	if strings.HasPrefix(lower, "bool") {
		return "boolean"
	}
	if strings.HasPrefix(lower, "json") {
		return "Record<string, any>"
	}
	return "string"
}

func toPascalCase(str string) string {
	parts := strings.FieldsFunc(str, func(r rune) bool {
		return r == '_' || r == '-' || r == ' '
	})
	var b strings.Builder
	for _, p := range parts {
		if len(p) > 0 {
			b.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	if b.Len() == 0 {
		return "Table"
	}
	return b.String()
}

var schemaCmd = &cobra.Command{
	Use:   "schema",
	Short: "Introspect database schemas and generate types",
}

var schemaPullCmd = &cobra.Command{
	Use:   "pull <database>",
	Short: "Pull structured schema for a database from information_schema and pg_catalog",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		dbName := args[0]
		resp, err := apiCli.GetSchema(dbName)
		if err != nil {
			return fmt.Errorf("failed to introspect schema: %w", err)
		}

		if flagFormat == "json" {
			data, _ := json.MarshalIndent(resp, "", "  ")
			fmt.Println(string(data))
			return nil
		}

		tables, _ := resp["tables"].([]any)
		if len(tables) == 0 {
			fmt.Printf("No user tables found in schema 'public' for database '%s'.\n", dbName)
			return nil
		}

		fmt.Printf("=== Schema for %s (public) ===\n\n", dbName)
		for _, t := range tables {
			tbl, ok := t.(map[string]any)
			if !ok {
				continue
			}

			fmt.Printf("TABLE %v (%v rows)\n", tbl["name"], tbl["rows"])
			w := tabwriter.NewWriter(os.Stdout, 0, 0, 3, ' ', 0)
			fmt.Fprintln(w, "  COLUMN\tTYPE\tNULLABLE\tFLAG")

			cols, _ := tbl["cols"].([]any)
			for _, c := range cols {
				col, ok := c.(map[string]any)
				if !ok {
					continue
				}
				flag := col["flag"]
				if flag == nil {
					flag = ""
				}
				nullStr := "NO"
				if isNull, _ := col["is_nullable"].(bool); isNull {
					nullStr = "YES"
				}
				fmt.Fprintf(w, "  %v\t%v\t%v\t%v\n", col["name"], col["type"], nullStr, flag)
			}
			w.Flush()
			fmt.Println()
		}

		return nil
	},
}

var schemaTypesCmd = &cobra.Command{
	Use:   "types <database>",
	Short: "Generate TypeScript type definitions (.d.ts) from database schema",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		dbName := args[0]
		resp, err := apiCli.GetSchema(dbName)
		if err != nil {
			return fmt.Errorf("failed to introspect schema: %w", err)
		}

		tables, _ := resp["tables"].([]any)
		if len(tables) == 0 {
			fmt.Printf("// No user tables found in database '%s'.\n", dbName)
			return nil
		}

		fmt.Printf("/**\n * Auto-generated TypeScript definitions for PostgreSQL Database: %s\n * Generated by VPSQL CLI\n */\n\n", dbName)

		var generatedTables []string
		for _, t := range tables {
			tbl, ok := t.(map[string]any)
			if !ok {
				continue
			}
			tName, _ := tbl["name"].(string)
			if flagTableFilter != "" && tName != flagTableFilter {
				continue
			}

			generatedTables = append(generatedTables, tName)
			ifName := toPascalCase(tName)
			fmt.Printf("export interface %s {\n", ifName)

			cols, _ := tbl["cols"].([]any)
			for _, c := range cols {
				col, ok := c.(map[string]any)
				if !ok {
					continue
				}
				cName, _ := col["name"].(string)
				cType, _ := col["type"].(string)
				isNull, _ := col["is_nullable"].(bool)

				tsType := pgTypeToTs(cType)
				optional := ": "
				nullSuffix := ""
				if isNull {
					optional = "?: "
					nullSuffix = " | null"
				}
				fmt.Printf("  %s%s%s%s;\n", cName, optional, tsType, nullSuffix)
			}
			fmt.Println("}")
			fmt.Println()
		}

		if flagTableFilter == "" && len(generatedTables) > 0 {
			fmt.Println("export interface DatabaseTables {")
			for _, t := range generatedTables {
				fmt.Printf("  %s: %s;\n", t, toPascalCase(t))
			}
			fmt.Println("}")
		}

		return nil
	},
}

func init() {
	schemaPullCmd.Flags().StringVar(&flagFormat, "format", "table", "Output format: table or json")
	schemaTypesCmd.Flags().StringVarP(&flagTableFilter, "table", "t", "", "Generate types only for a specific table")

	schemaCmd.AddCommand(schemaPullCmd)
	schemaCmd.AddCommand(schemaTypesCmd)
	rootCmd.AddCommand(schemaCmd)
}
