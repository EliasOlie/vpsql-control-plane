import { TableSchema } from './api';

export function pgTypeToTs(pgType: string): string {
  const lower = pgType.toLowerCase().trim();
  
  if (lower.endsWith('[]')) {
    const base = lower.slice(0, -2);
    return `${pgTypeToTs(base)}[]`;
  }

  if (
    lower.startsWith('int') || 
    lower.startsWith('smallint') || 
    lower.startsWith('bigint') || 
    lower.startsWith('decimal') || 
    lower.startsWith('numeric') || 
    lower.startsWith('real') || 
    lower.startsWith('double') || 
    lower.startsWith('float') || 
    lower.startsWith('serial')
  ) {
    return 'number';
  }

  if (lower.startsWith('bool')) {
    return 'boolean';
  }

  if (lower.startsWith('json')) {
    return 'Record<string, any>';
  }

  // strings, dates, uuids, timestamps
  return 'string';
}

export function toPascalCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/^[a-z]/, chr => chr.toUpperCase());
}

export function generateTableInterface(table: TableSchema): string {
  const interfaceName = toPascalCase(table.name);
  const lines = [`export interface ${interfaceName} {`];
  table.cols.forEach(c => {
    const tsType = pgTypeToTs(c.type);
    const optional = c.is_nullable ? '?: ' : ': ';
    const nullType = c.is_nullable ? ' | null' : '';
    lines.push(`  ${c.name}${optional}${tsType}${nullType};`);
  });
  lines.push('}');
  return lines.join('\n');
}

export function generateAllInterfaces(tables: TableSchema[], databaseName?: string): string {
  const header = `/**\n * Auto-generated TypeScript definitions for PostgreSQL Database: ${databaseName || 'VPSQL'}\n * Generated by VPSQL on ${new Date().toLocaleDateString()}\n */\n\n`;
  const tableInterfaces = tables.map(generateTableInterface).join('\n\n');
  const databaseMap = `\n\nexport interface DatabaseTables {\n${tables.map(t => `  ${t.name}: ${toPascalCase(t.name)};`).join('\n')}\n}\n`;
  return header + tableInterfaces + databaseMap;
}
